export type Ru = typeof ru;

/** Сообщение об ошибке tRPC по коду/ключу (SPEC §15). */
export function errorMessage(codeOrKey: string | undefined): string {
  if (!codeOrKey) return ru.errors.INTERNAL_SERVER_ERROR;
  const table = ru.errors as unknown as Record<string, unknown>;
  const v = table[codeOrKey];
  return typeof v === 'string' ? v : ru.errors.INTERNAL_SERVER_ERROR;
}
